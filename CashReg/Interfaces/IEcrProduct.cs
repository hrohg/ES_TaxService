using System.Runtime.InteropServices;

namespace CashReg.Interfaces
{
    /// <summary>
    /// Ապրանք
    /// </summary>
    //[ComVisible(true)]
    public interface IEcrProduct
    {
        /// <summary>
        /// Ապրանքի բաժին
        /// </summary>
        int dep { get; set; }
        
        /// <summary>
        /// Ապրանքի քանակ: 
        /// Ստորակետից հետո թույլատրվում է առավելագույնը 3 նիշ:
        /// </summary>        
        decimal qty { get; set; }
        
        /// <summary>
        /// Ապրանքի զեղչ: 
        /// Ստորակետից հետո առավելագույնը 2 նիշ (եթե ապրանքի վրա զողչ չի կիրառվել, ապա դաշտը չպետք է ուղարկվի):
        /// </summary>        
        decimal? discount { get; set; }
        
        /// <summary>
        /// Ինչ տիպի զեղչ է կատարվել, դրամային ապրանքների տողերի վրա կամ %-ային ապրանքների տողերի վրա % - ային զեղչի դեպքում ընդունում է 8 արժեքը, 
        /// դրամային զեղչի դեպքում ընդունում է 16 արժեքը: Եթե համապատասխան զեղչ չի կիրառվում, ապա տվյալը պետք չէ ուղարկել:
        /// </summary>        
        int? discountType { get; set; }
        
        /// <summary>
        /// Ապրանքի լրացուցիչ զեղչ: Ստորակետից հետո առավելագույնը 2 նիշ (եթե ապրանքի վրա զողչ չի կիրառվել, ապա դաշտը չպետք է ուղարկվի):
        /// </summary>        
        decimal? additionalDiscount { get; set; }
        
        /// <summary>
        /// Ինչ տիպի զեղչ է կատարվել, դրամային ապրանքների տողերի վրա կամ %-ային ապրանքների տողերի վրա % - ային զեղչի դեպքում
        /// ընդունում է 8 արժեքը, դրամային զեղչի դեպքում ընդունում է 16 արժեքը: Եթե համապատասխան զեղչ չի կիրառվում, ապա տվյալը պետք չէ ուղարկել:
        /// </summary>        
        int? additionalDiscountType { get; set; }
        
        /// <summary>
        /// Ապրանքի միավոր գին: Ստորակետից հետո առավելագույնը 2 նիշ:
        /// </summary>        
        decimal price { get; set; }
        
        /// <summary>
        /// Ապրանքի կոդ (Առավելագույնը 50 նիշ, չի կարող լինել դատարկ)
        /// </summary>        
        string productCode { get; set; }
        
        /// <summary>
        /// Ապրանքի անվանումը (Առավելագույնը 50 նիշ, չի կարող լինել դատարկ)
        /// </summary>        
        string productName { get; set; }
        
        /// <summary>
        /// Ապրանքի ԱՏԳ կոդ: Պետք է լինի համապատասխան ցանկից, 
        /// որը կարելի է գտնել taxservice.am կայքում մուտք գործելով ԷԼԵԿՏՐՈՆԱՅԻՆ ԾԱՌԱՅՈՒԹՅՈՒՆՆԵՐ բաժնի 
        /// ՆՈՐ ՍԵՐՆԴԻ ՀՍԿԻՉ-ԴՐԱՄԱՐԿՂԱՅԻՆ ՄԵՔԵՆԱՆԵՐ ենթաբաժին, 
        /// որտեղ վերջում կան երկու Excel փաստաթղթեր՝ N 1406-Ն և N 875-Ն որոնք և պարունակում են ԱՏԳ կոդերը:
        /// </summary>        
        string adgCode { get; set; }
        
        /// <summary>
        /// Չափման միավորը (Առավելագույնը 50 նիշ, չի կարող լինել դատարկ)
        /// </summary>
        string unit { get; set; }
    }
}